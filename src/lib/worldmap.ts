export const WORLD_COLS = 72;
export const WORLD_LINES = WORLD_ROWS.length;

export function isLand(col: number, row: number): boolean {
  if (row < 0 || row >= WORLD_LINES) return false;
  const line = WORLD_ROWS[row];
  const c = ((col % WORLD_COLS) + WORLD_COLS) % WORLD_COLS;
  return line[c] === "#";
}
