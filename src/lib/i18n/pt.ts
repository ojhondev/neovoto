/** Widen literais (string/number/tuplas) para que outros idiomas satisfaçam o mesmo formato. */
type Widen<T> = T extends string
  ? string
  : T extends number
    ? number
    : T extends readonly (infer U)[]
      ? readonly Widen<U>[]
      : { [K in keyof T]: Widen<T[K]> };

